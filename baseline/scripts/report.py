"""Aggregate evaluation episodes (baseline/results/eval/<policy>/<suite>.jsonl) into tables and a summary JSON.

    python baseline/scripts/report.py                     # -> baseline/results/RESULTS_TABLES.md, summary.json

Success rates come with Wilson 95% intervals. "Stages" are cumulative flags from simulation ground truth:
approached (TCP came within 5 cm of the designated book's spine, closer than to any other book), contact (both pads
press the designated book > 1 N), moved (pulled > 2 cm), extracted (fully out of the shelf), lifted (3 cm above the
board), success (lifted + held by both pads for 1 s).
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
SUITE_ORDER = ["nominal", "random", "narrow", "heavy_lowmu"]
POLICY_LABEL = {"expert": "Scripted expert (privileged, upper bound)",
                "pi05_droid": "π0.5-DROID, zero-shot (retargeted)",
                "pi05_ft": "π0.5 fine-tuned (LoRA, 251 demos)",
                "pi05_droid_nostop": "π0.5-DROID zero-shot, protective stop off (diagnostic)"}


def wilson(k: int, n: int, z: float = 1.96):
    if n == 0:
        return float("nan"), float("nan")
    p = k / n
    den = 1 + z * z / n
    c = (p + z * z / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return max(0.0, c - h), min(1.0, c + h)


def load(eval_dir: Path):
    data = {}
    for pdir in sorted(p for p in eval_dir.iterdir() if p.is_dir()):
        for f in sorted(pdir.glob("*.jsonl")):
            rows = [json.loads(line) for line in open(f)]
            ok = [r for r in rows if "error" not in r]
            if ok:
                data.setdefault(pdir.name, {})[f.stem] = {"rows": ok, "errors": len(rows) - len(ok)}
    return data


def summarize(rows):
    n = len(rows)
    k = sum(r["success"] for r in rows)
    lo, hi = wilson(k, n)
    frac = lambda key: float(np.mean([bool(r.get(key)) for r in rows])) if n else float("nan")
    med = lambda key: float(np.median([r[key] for r in rows if r.get(key) is not None])) if n else float("nan")
    t_succ = [r["t_success"] for r in rows if r.get("success") and "t_success" in r]
    out = {
        "n": n, "success": k, "rate": k / n if n else float("nan"), "ci95": [lo, hi],
        "approached": frac("approached_target"), "contact": frac("stage_contact"), "moved": frac("stage_moved"),
        "extracted": frac("stage_extracted"), "lifted": frac("stage_lifted"),
        "protective_stop": frac("protective_stop"), "wrong_book": frac("wrong_book"), "dropped": frac("stage_dropped"),
        "others_disturbed_5mm": float(np.mean([r["others_moved_gt_5mm"] > 0 for r in rows])),
        "others_max_disp_mm_median": med("others_max_disp_mm"),
        "hard_contact_N_median": med("hard_contact_max_N"),
        "wrist_force_N_median": med("wrist_force_max_N"),
        "pad_force_N_median": med("pad_force_max_N"),
        "time_to_success_s_median": float(np.median(t_succ)) if t_succ else float("nan"),
        "latency_s_mean": float(np.mean([r["policy_latency_s"] for r in rows if "policy_latency_s" in r]))
        if any("policy_latency_s" in r for r in rows) else float("nan"),
    }
    dis = [r for r in rows if r.get("distractor")]
    if dis:
        out["distractor_n"], out["distractor_success"] = len(dis), sum(r["success"] for r in dis)
    return out


def pct(x):
    return "–" if x != x else f"{100 * x:.0f}%"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval-dir", type=Path, default=ROOT / "baseline" / "results" / "eval")
    ap.add_argument("--out", type=Path, default=ROOT / "baseline" / "results")
    args = ap.parse_args()
    data = load(args.eval_dir)
    summary = {p: {s: summarize(v["rows"]) | {"errors": v["errors"]} for s, v in suites.items()}
               for p, suites in data.items()}
    (args.out / "summary.json").write_text(json.dumps(summary, indent=1))
    lines = ["# Evaluation tables (generated by baseline/scripts/report.py)", ""]
    lines += ["## Success rate (Wilson 95% CI)", "",
              "| Policy | " + " | ".join(SUITE_ORDER) + " |", "|---|" + "---|" * len(SUITE_ORDER)]
    for p, suites in summary.items():
        cells = []
        for s in SUITE_ORDER:
            if s in suites:
                r = suites[s]
                cells.append(f"{r['success']}/{r['n']} = {pct(r['rate'])} [{pct(r['ci95'][0])}, {pct(r['ci95'][1])}]")
            else:
                cells.append("not run")
        lines.append(f"| {POLICY_LABEL.get(p.split('_step')[0], p)} (`{p}`) | " + " | ".join(cells) + " |")
    lines += ["", "## Stage funnel and safety (fraction of episodes)", "",
              "| Policy | Suite | n | approached | contact | moved | extracted | lifted | **success** | protective stop |"
              " wrong book | other books moved >5 mm | median max hard contact (N) | median time to success (s) |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p, suites in summary.items():
        for s in SUITE_ORDER:
            if s not in suites:
                continue
            r = suites[s]
            t = r["time_to_success_s_median"]
            lines.append(f"| `{p}` | {s} | {r['n']} | {pct(r['approached'])} | {pct(r['contact'])} | {pct(r['moved'])} | "
                         f"{pct(r['extracted'])} | {pct(r['lifted'])} | **{pct(r['rate'])}** | "
                         f"{pct(r['protective_stop'])} | {pct(r['wrong_book'])} | {pct(r['others_disturbed_5mm'])} | "
                         f"{r['hard_contact_N_median']:.0f} | {'–' if t != t else f'{t:.1f}'} |")
    dis = [(p, s, r) for p, suites in summary.items() for s, r in suites.items() if "distractor_n" in r]
    if dis:
        lines += ["", "## Language grounding: episodes with a second gapped book of another colour", "",
                  "| Policy | Suite | success with distractor | success without |", "|---|---|---|---|"]
        for p, s, r in dis:
            rows = data[p][s]["rows"]
            no = [x for x in rows if not x.get("distractor")]
            lines.append(f"| `{p}` | {s} | {r['distractor_success']}/{r['distractor_n']} | "
                         f"{sum(x['success'] for x in no)}/{len(no)} |")
    ins = [(p, su, data[p][su]["rows"]) for p in data for su in SUITE_ORDER
           if su in data[p] and any("insert_lateral_mm" in r for r in data[p][su]["rows"])]
    if ins:
        lines += ["", "## Blade insertion: where the TCP crossed the plane of the spines", "",
                  "Lateral = TCP offset from the designated book's centre line; each pad has 3 mm of air at a perfect "
                  "insertion (less in the narrow suite).", "",
                  "| Policy | Suite | crossed | median abs lateral (mm) | abs lateral > 3 mm | success if <= 3 mm | "
                  "success if > 3 mm | median depth (mm) |", "|---|---|---|---|---|---|---|---|"]
        for p, su, rows in ins:
            c = [r for r in rows if "insert_lateral_mm" in r]
            lat = np.abs([r["insert_lateral_mm"] for r in c])
            good = [r for r in c if abs(r["insert_lateral_mm"]) <= 3.0]
            bad = [r for r in c if abs(r["insert_lateral_mm"]) > 3.0]
            frac = lambda xs: f"{sum(x['success'] for x in xs)}/{len(xs)}" if xs else "–"
            lines.append(f"| `{p}` | {su} | {len(c)}/{len(rows)} | {np.median(lat):.1f} | {pct(float(np.mean(lat > 3.0)))} | "
                         f"{frac(good)} | {frac(bad)} | {np.median([r['insert_depth_mm'] for r in rows]):.0f} |")
    (args.out / "RESULTS_TABLES.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
