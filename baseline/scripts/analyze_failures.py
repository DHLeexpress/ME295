"""Classify every failed episode into one failure mode (first that applies), per policy and suite.

    python baseline/scripts/analyze_failures.py            # -> baseline/results/FAILURES.md

Modes, in the order of the task:
    protective stop     the wrist force exceeded 150 N (the arm hit the shelf or books hard)
    wrong book          another book was pulled > 5 cm toward the robot
    never reached       the TCP never came within 5 cm of the designated book's spine (closer than to any other)
    insertion miss      the TCP crossed the spine plane > 3 mm off the book's centre line (a blade lands on the spine
                        or on the neighbour), or never crossed it
    pushed in           inserted within 3 mm, but the blade tips pushed the book > 2 cm deeper into the shelf and the
                        pads never touched it (from the trace: the book's depth y)
    jammed              inserted within 3 mm, but the book was never pulled > 2 cm (pads squeezed it, or no trace)
    partial pull        pulled > 2 cm but not out of the shelf
    slipped in lift     out of the shelf but not lifted and held for 1 s (slip / drop / tilt)
Insertion-based modes need traces (evaluations run after traces were added); otherwise "jammed / insertion miss
(no trace)" is reported.
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODES = ["protective stop", "wrong book", "never reached", "insertion miss", "pushed in", "jammed",
         "jammed / insertion miss (no trace)", "partial pull", "slipped in lift", "other"]


def mode(r: dict, trace=None) -> str:
    """trace: the episode's (T, 9) trace (t, TCP xyz, book xyz, gripper, |F|), if recorded."""
    if r.get("protective_stop"):
        return "protective stop"
    if r.get("wrong_book"):
        return "wrong book"
    if not r.get("approached_target"):
        return "never reached"
    if not r.get("stage_moved"):
        if "insert_depth_mm" not in r:
            return "jammed / insertion miss (no trace)"
        lat = r.get("insert_lateral_mm")
        if lat is None or abs(lat) > 3.0:
            return "insertion miss"
        if trace is not None and not r.get("stage_contact") and trace[:, 5].max() - trace[0, 5] > 0.02:
            return "pushed in"
        return "jammed"
    if not r.get("stage_extracted"):
        return "partial pull"
    if not r.get("success"):
        return "slipped in lift"
    return "other"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--eval-dir", type=Path, default=ROOT / "baseline" / "results" / "eval")
    ap.add_argument("--out", type=Path, default=ROOT / "baseline" / "results" / "FAILURES.md")
    args = ap.parse_args()
    lines = ["# Failure modes (generated by baseline/scripts/analyze_failures.py)", "",
             "Each failed episode counted once, in the first mode that applies (see the script's docstring).", "",
             "| Policy | Suite | failures | " + " | ".join(MODES) + " |", "|---|---|---|" + "---|" * len(MODES)]
    for pdir in sorted(p for p in args.eval_dir.iterdir() if p.is_dir()):
        for su in ("nominal", "random", "narrow", "heavy_lowmu"):
            f = pdir / f"{su}.jsonl"
            if not f.exists():
                continue
            rows = [json.loads(x) for x in open(f)]
            fails = [r for r in rows if "error" not in r and not r.get("success")]
            c = Counter(mode(r, load_trace(pdir, su, r["index"])) for r in fails)
            lines.append(f"| `{pdir.name}` | {su} | {len(fails)}/{len(rows)} | " +
                         " | ".join(str(c.get(m, "")) for m in MODES) + " |")
    lines += preshape_table(args.eval_dir)
    args.out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


def load_trace(pdir: Path, suite: str, index: int):
    import numpy as np
    f = pdir / "traces" / f"{suite}_{index:03d}.npy"
    return np.load(f) if f.exists() else None


def preshape_table(eval_dir: Path) -> list:
    """Jaw opening when the blades crossed the plane of the spines, minus the book's thickness, by thickness (from
    the traces). The expert opens to the book + 6 mm (3 mm per side)."""
    import sys
    import numpy as np
    sys.path.insert(0, str(ROOT))
    from baseline.embodiment import EndEffector
    ee = EndEffector.load()
    out = ["", "## Jaw pre-shape vs book thickness (blades crossing the spine plane)", "",
           "Pad gap minus book thickness when the TCP crossed the spines (expert: +6.0 mm). Median [min, max], success.",
           "", "| Policy | Suite | thickness (mm) | n | gap - thickness (mm) | success |", "|---|---|---|---|---|---|"]
    for pdir in sorted(p for p in eval_dir.iterdir() if p.is_dir() and (p / "traces").exists()):
        for su in ("nominal", "random", "narrow", "heavy_lowmu"):
            f = pdir / f"{su}.jsonl"
            if not f.exists():
                continue
            groups = {}
            for line in open(f):
                r = json.loads(line)
                tpath = pdir / "traces" / f"{su}_{r['index']:03d}.npy"
                if "error" in r or not tpath.exists():
                    continue
                tr = np.load(tpath)
                spine = 0.82
                k = np.where((tr[:-1, 2] < spine) & (tr[1:, 2] >= spine))[0]
                margin = (ee.width_for_register(tr[k[0] + 1, 7] * 255) * 1e3 - r["thickness_mm"]) if len(k) else None
                groups.setdefault(r["thickness_mm"], []).append((margin, r["success"]))
            for th in sorted(groups):
                g = groups[th]
                m = [x for x, _ in g if x is not None]
                spread = f"{np.median(m):+.1f} [{min(m):+.1f}, {max(m):+.1f}]" if m else "never crossed"
                out.append(f"| `{pdir.name}` | {su} | {th:.0f} | {len(g)} | {spread} | {sum(s for _, s in g)}/{len(g)} |")
    return out


if __name__ == "__main__":
    main()
