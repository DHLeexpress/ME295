"""Simulated PDMS skin: per-taxel contact force and deformation of the blade's PDMS layer.

The PDMS layer on each blade is a deformable body (assembly/pdms_{side}.xml, generated by
scripts_sim/make_blade_assets.py), bonded to the blade at its back face, either
  flex   a 3D finite-element flex ({side}_pdms_flex): the free face is its surface, the deformation its vertex
         displacements; or
  cells  nx x ny columns of PDMS, each on three elastic slide joints (thin-layer / Winkler limit) touching objects
         at one point; the deformation is the joint positions.
The face is read on a grid of taxels (5 x 7 for the flex, the cells otherwise), in the PDMS frame (x across the
blade width, y along the finger toward the tip, z the face normal, +z into the layer / away from the object):

    normal[j, i]          contact force pressing into the skin (N, >= 0)      } MuJoCo's contact solver: the
    shear[j, i, :]        in-plane contact force (N): the object's drag       } contacts inside the taxel
    deformation[j, i, :]  displacement of the free face (m): [0], [1] shear, [2] compression (cells: the joint
                          positions; flex: the mean over the free-face vertices in the taxel)

i indexes the blade width (x), j the finger length (y, j = 0 at the proximal end).

These are idealised: what the layer feels and how it deforms, at the cell resolution of the model. What the
real sensor reports (its transduction, resolution, rate, noise, calibration) is not characterised yet; the
SkinSensor below only adds an assumed frame rate.
"""
from __future__ import annotations

import re
from dataclasses import dataclass, field

import mujoco
import numpy as np

from ..grasp_quality import friction_margin


@dataclass
class TactileFrame:
    normal: np.ndarray            # (ny, nx) N
    shear: np.ndarray             # (ny, nx, 2) N, PDMS frame (x across, y toward the tip)
    taxel_xy: np.ndarray          # (ny, nx, 2) cell centres in the PDMS frame (m)
    deformation: np.ndarray       # (ny, nx, 3) m: shear displacement x, y and compression z of each cell
    stiffness: np.ndarray = field(default_factory=lambda: np.zeros(3))  # (k_shear, k_shear, k_normal) N/m per
    #                             cell (cells model); for the flex the Winkler values of a taxel, for reference only
    mu: float = 1.0
    total_normal: float = 0.0
    total_shear: np.ndarray = field(default_factory=lambda: np.zeros(2))
    cop: np.ndarray = field(default_factory=lambda: np.full(2, np.nan))  # centre of pressure (m)
    stamp: float = 0.0            # simulated time the frame was taken (s)

    @property
    def in_contact(self) -> bool:
        return self.total_normal > 1e-6

    def elastic_force(self) -> np.ndarray:
        """(ny, nx, 3) force the layer's elasticity carries, stiffness x deformation (N): [shear x, shear y,
        normal]. Cells model: in quasi-static contact it equals the contact force. Flex: the Winkler estimate
        from the FEM deformation (exact only for a uniform load far from the edges)."""
        return self.deformation * self.stiffness

    def margin(self) -> np.ndarray:
        """Per-cell friction margin q = 1 - |shear| / (mu * normal) (grasp_quality.friction_margin)."""
        return friction_margin(np.linalg.norm(self.shear, axis=-1), self.normal, self.mu)

    def torsion(self) -> float:
        """Moment of the shear field about the skin normal through the centre of pressure (N m):
        the twist load, e.g. a heavy object hanging off-centre."""
        if not self.in_contact:
            return 0.0
        r = self.taxel_xy - self.cop
        return float(np.sum(r[..., 0] * self.shear[..., 1] - r[..., 1] * self.shear[..., 0]))

    def friction_radius(self, min_frac: float = 0.1) -> float:
        """(2/3) sqrt(A / pi) of the loaded area: torque capacity = mu * normal * radius (uniform pressure)."""
        dx = abs(self.taxel_xy[0, 1, 0] - self.taxel_xy[0, 0, 0])
        dy = abs(self.taxel_xy[1, 0, 1] - self.taxel_xy[0, 0, 1])
        loaded = self.normal > min_frac * float(self.normal.max(initial=0.0))
        return float(2.0 / 3.0 * np.sqrt(loaded.sum() * dx * dy / np.pi))

    def net_margin(self) -> float:
        """Margin of the whole patch against sliding and twisting, from an ellipsoidal limit surface:
        q = 1 - sqrt((|T| / (mu N))^2 + (|M| / (mu N r))^2), with T the summed shear, M the torsion
        and r the friction radius. 1 if not in contact, < 0 when the patch slips."""
        if not self.in_contact:
            return 1.0
        cap = self.mu * self.total_normal
        lin = np.linalg.norm(self.total_shear) / cap
        rot = abs(self.torsion()) / (cap * max(self.friction_radius(), 1e-4))
        return float(1.0 - np.hypot(lin, rot))

    def grasp_margin(self, min_normal: float = 0.05, min_frac: float = 0.1) -> float:
        """Weakest loaded cell: Q = min q over cells carrying > max(min_normal, min_frac * peak)
        normal force (nearly unloaded edge cells say little about slip); 1.0 if none."""
        loaded = self.normal > max(min_normal, min_frac * float(self.normal.max(initial=0.0)))
        return float(np.min(self.margin()[loaded])) if loaded.any() else 1.0


def _frame(normal, shear, deformation, skin, stamp) -> TactileFrame:
    total = float(normal.sum())
    cop = (normal[..., None] * skin.xy).sum((0, 1)) / total if total > 1e-9 else np.full(2, np.nan)
    return TactileFrame(normal=normal, shear=shear, taxel_xy=skin.xy, deformation=deformation,
                        stiffness=skin.k, mu=skin.mu, total_normal=total, total_shear=shear.sum((0, 1)),
                        cop=cop, stamp=stamp)


class PDMSSkin:
    """Reads the PDMS layer of one blade ("left" or "right"): a flex or cells (see the module docstring)."""

    _PAT = re.compile(r"^(left|right)_pdms_(\d+)_(\d+)$")

    def __init__(self, m: mujoco.MjModel, side: str, mu: float | None = None, taxels: tuple = (5, 7)):
        self.m, self.side = m, side
        self.body = m.body(f"{side}_pdms").id
        box = m.geom(f"{side}_pdms").id
        self.half = m.geom_size[box].copy()                    # a/2, b/2, t/2 of the layer
        self._elliptic = m.opt.cone == mujoco.mjtCone.mjCONE_ELLIPTIC
        self._f6 = np.zeros(6)
        self.flex = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_FLEX, f"{side}_pdms_flex")  # -1: cells model
        if self.flex >= 0:
            self._init_flex(m, mu, taxels)
        else:
            self._init_cells(m, mu)

    def _init_cells(self, m, mu):
        idx = []
        for g in range(m.ngeom):
            hit = self._PAT.match(m.geom(g).name or "")
            if hit and hit.group(1) == self.side:
                idx.append((g, int(hit.group(2)), int(hit.group(3))))
        if not idx:
            raise ValueError(f"no PDMS cells or flex for {self.side}; regenerate assembly/pdms_{self.side}.xml")
        self.nx = 1 + max(i for _, i, _ in idx)
        self.ny = 1 + max(j for _, _, j in idx)
        self.xy = np.zeros((self.ny, self.nx, 2))
        self.qadr = np.zeros((self.ny, self.nx, 3), int)   # qpos of the x, y, z joints of each cell
        for g, i, j in idx:
            cell = m.geom_bodyid[g]
            self.xy[j, i] = (m.body_pos[cell] - m.body_pos[self.body])[:2]  # both relative to the fingertip
            for k, ax in enumerate("xyz"):
                self.qadr[j, i, k] = m.jnt_qposadr[m.joint(f"{self.side}_pdms_{i}_{j}_{ax}").id]
        j0 = m.joint(f"{self.side}_pdms_0_0_x").id, m.joint(f"{self.side}_pdms_0_0_z").id
        self.k = np.array([m.jnt_stiffness[j0[0]], m.jnt_stiffness[j0[0]], m.jnt_stiffness[j0[1]]])
        self.mu = float(mu if mu is not None else m.geom_friction[idx[0][0]][0])
        self._lut = np.full(m.ngeom, -1)
        for g, i, j in idx:
            self._lut[g] = j * self.nx + i

    def _init_flex(self, m, mu, taxels):
        self.nx, self.ny = taxels
        a, b, t = 2 * self.half
        dx, dy = a / self.nx, b / self.ny
        xs = -a / 2 + (np.arange(self.nx) + 0.5) * dx
        ys = -b / 2 + (np.arange(self.ny) + 0.5) * dy
        self.xy = np.stack(np.meshgrid(xs, ys), -1)          # (ny, nx, 2) taxel centres
        self._grid = (a, b, dx, dy)
        # free-face vertices (rest pose, PDMS frame) and their share of each taxel (boundary vertices are shared)
        d = mujoco.MjData(m)
        mujoco.mj_kinematics(m, d)
        mujoco.mj_flex(m, d)
        adr, num = m.flex_vertadr[self.flex], m.flex_vertnum[self.flex]
        R, p = d.xmat[self.body].reshape(3, 3), d.xpos[self.body]
        rest = (d.flexvert_xpos[adr:adr + num] - p) @ R
        face = np.where(np.abs(rest[:, 2] + t / 2) < 1e-3 * t)[0]
        self.vert = adr + face
        self.rest = rest[face]
        W = np.zeros((self.ny * self.nx, face.size))
        tol = 1e-6
        for k, (x, y) in enumerate(self.rest[:, :2]):
            ii = [i for i in range(self.nx) if -a / 2 + i * dx - tol <= x <= -a / 2 + (i + 1) * dx + tol]
            jj = [j for j in range(self.ny) if -b / 2 + j * dy - tol <= y <= -b / 2 + (j + 1) * dy + tol]
            for i in ii:
                for j in jj:
                    W[j * self.nx + i, k] = 1.0
        self.W = W / W.sum(1, keepdims=True)
        self.k = np.zeros(3)   # no per-taxel spring in the FEM (set_winkler_reference() fills the Winkler values)
        self.mu = float(mu if mu is not None else m.flex_friction[self.flex][0])

    def read(self, d: mujoco.MjData) -> TactileFrame:
        normal = np.zeros(self.ny * self.nx)
        shear = np.zeros((self.ny * self.nx, 2))
        n = d.ncon
        R = d.xmat[self.body].reshape(3, 3)
        if n:
            if self.flex >= 0:
                fl = d.contact.flex[:n]
                on1, on2 = fl[:, 0] == self.flex, fl[:, 1] == self.flex
                hit = np.where(on1 | on2)[0]
                if hit.size:
                    local = (d.contact.pos[hit] - d.xpos[self.body]) @ R
                    a, b, dx, dy = self._grid
                    i = np.clip(((local[:, 0] + a / 2) / dx).astype(int), 0, self.nx - 1)
                    j = np.clip(((local[:, 1] + b / 2) / dy).astype(int), 0, self.ny - 1)
                    taxel = j * self.nx + i
                    sign = np.where(on2[hit], 1.0, -1.0)   # the solver's force acts on the second object
            else:
                g1, g2 = d.contact.geom1[:n], d.contact.geom2[:n]
                t1, t2 = self._lut[g1], self._lut[g2]
                hit = np.where((t1 >= 0) | (t2 >= 0))[0]
                if hit.size:
                    taxel = np.where(t2[hit] >= 0, t2[hit], t1[hit])
                    sign = np.where(t2[hit] >= 0, 1.0, -1.0)   # the solver's force acts on geom2
            if hit.size:
                if self._elliptic:  # contact-frame force = first three efc rows (normal, t1, t2)
                    adr = d.contact.efc_address[hit]
                    f = d.efc_force[adr[:, None] + np.arange(3)]
                else:
                    f = np.array([self._force(d, c) for c in hit])
                frames = d.contact.frame[hit].reshape(-1, 3, 3)          # rows: normal, t1, t2 (world)
                f_world = sign[:, None] * np.einsum("kij,ki->kj", frames, f)
                f_pdms = f_world @ R                                       # = R^T f per contact
                np.add.at(normal, taxel, f_pdms[:, 2])   # +z of the skin points away from the object
                np.add.at(shear, taxel, f_pdms[:, :2])
        normal = np.clip(normal.reshape(self.ny, self.nx), 0.0, None)
        return _frame(normal, shear.reshape(self.ny, self.nx, 2), self.deformation(d), self, float(d.time))

    def deformation(self, d: mujoco.MjData) -> np.ndarray:
        """(ny, nx, 3) displacement of the free face per taxel (m), PDMS frame, +z = compression."""
        if self.flex < 0:
            return d.qpos[self.qadr].copy()
        R = d.xmat[self.body].reshape(3, 3)
        u = (d.flexvert_xpos[self.vert] - d.xpos[self.body]) @ R - self.rest
        return (self.W @ u).reshape(self.ny, self.nx, 3)

    def _force(self, d, c) -> np.ndarray:
        mujoco.mj_contactForce(self.m, d, int(c), self._f6)
        return self._f6[:3].copy()


class SkinSensor:
    """The skin at an assumed frame rate: frames at `rate_hz`, each the average of the samples taken at
    every control tick during the frame (the rate is a placeholder: the real sensor's is not known yet).
    Attach with `rob.callbacks.append(sensor.tick)`; `latest` is what a controller sees, `raw` the last sample."""

    def __init__(self, skin: PDMSSkin, rate_hz: float = 20.0):
        self.skin, self.period = skin, 1.0 / rate_hz
        self.latest: TactileFrame = skin.read(mujoco.MjData(skin.m))
        self.raw = self.latest
        self._acc, self._n, self._t_next = None, 0, 0.0

    def tick(self, rob) -> None:
        f = self.raw = self.skin.read(rob.d)
        if self._acc is None:
            self._acc = [np.zeros_like(f.normal), np.zeros_like(f.shear), np.zeros_like(f.deformation)]
        self._acc[0] += f.normal
        self._acc[1] += f.shear
        self._acc[2] += f.deformation
        self._n += 1
        if rob.time + 1e-9 >= self._t_next:
            self.latest = _frame(*(a / self._n for a in self._acc), self.skin, rob.time)
            self._acc, self._n = None, 0
            self._t_next = rob.time + self.period

    def read(self, d=None) -> TactileFrame:
        """Same call as PDMSSkin.read, so controllers can take either."""
        return self.latest
